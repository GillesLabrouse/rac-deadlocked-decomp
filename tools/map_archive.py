#!/usr/bin/env python3
"""
Pair the functions of a Sony library archive (libc.a, libm.a, ...) with retail
functions, by code with relocatable fields masked, and write
config/<name>.tsv: member, symbol, address, size.

The archive is only a reference for naming and address mapping (the library
symbol names are public); matching still requires compiling real source.
Usage: venv/bin/python tools/map_archive.py ARCHIVE.a NAME
"""
import os
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import retail as mp  # noqa: E402
from reloc_compare import function_relocations, relocated_equal  # noqa: E402
from elftools.elf.elffile import ELFFile  # noqa: E402

ROOT = mp.ROOT


def unique_candidate(code, relocations, candidates, taken=()):
    """Return one relocation-compatible hint; constants and ambiguity matter.

    This is archive navigation, not resolved symbol or matching-source proof.
    Only terminal zero padding of at most seven bytes is permitted.
    """
    hits = []
    for address, name, reference in candidates:
        padding = len(reference) - len(code)
        if not 0 <= padding <= 7 or any(reference[len(code):]):
            continue
        if relocated_equal(code, reference[:len(code)], relocations):
            hits.append((address, name, len(reference)))
    return hits[0] if len(hits) == 1 and hits[0][1] not in taken else None


def main() -> int:
    archive, name = sys.argv[1], sys.argv[2]
    funcs = []
    for l in (ROOT / "config" / "functions.tsv").read_text().splitlines()[1:]:
        n, a, s, seg = l.split("\t")
        funcs.append((int(a, 16), int(s, 16), n))
    with open(ROOT / "baserom" / "SCUS_974.65.elf", "rb") as f:
        secs = mp.sections(ELFFile(f))
    by_size = {}
    for a, s, n in funcs:
        by_size.setdefault(s, []).append((a, n, mp.read(secs, a, s)))
    rows, taken = [], set()
    with tempfile.TemporaryDirectory() as d:
        subprocess.run(["ar", "x", os.path.abspath(archive)], cwd=d, check=True)
        for obj in sorted(os.listdir(d)):
            with open(os.path.join(d, obj), "rb") as stream:
                try:
                    elf = ELFFile(stream)
                    text = elf.get_section_by_name(".text")
                    symbols = elf.get_section_by_name(".symtab")
                    if text is None or symbols is None:
                        continue
                    data = text.data()
                    section_index = elf.get_section_index(".text")
                    syms = [s for s in symbols.iter_symbols()
                            if s["st_info"]["type"] == "STT_FUNC" and s["st_size"]
                            and s["st_shndx"] == section_index]
                except Exception:  # noqa: BLE001
                    continue
                for s in syms:
                    start, length = s["st_value"], s["st_size"]
                    if start < 0 or start + length > len(data):
                        continue
                    code = data[start:start + length]
                    candidates = [candidate
                                  for size in sorted({length, (length + 7) & ~7})
                                  for candidate in by_size.get(size, [])]
                    try:
                        hit = unique_candidate(code, function_relocations(elf, s), candidates, taken)
                    except ValueError:
                        # Unknown relocation types cannot justify a mapping hint.
                        continue
                    if hit is not None:
                        address, function, size = hit
                        taken.add(function)
                        rows.append((obj, s.name, address, size))
    rows.sort(key=lambda r: r[2])
    with open(ROOT / "config" / (name + ".tsv"), "w") as f:
        f.write("# member\tsymbol\taddress\tsize  (generated by tools/map_archive.py from %s)\n" % Path(archive).name)
        for o, sym, a, sz in rows:
            f.write("%s\t%s\t0x%08X\t0x%X\n" % (o, sym, a, sz))
    print("%s: %d functions mapped, %d bytes" % (name, len(rows), sum(r[3] for r in rows)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
